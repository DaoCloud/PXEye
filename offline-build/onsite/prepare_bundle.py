#!/usr/bin/env python3
"""Check prerequisites, unpack/verify a delivery and generate shell activation."""
import argparse
import json
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile
import os

sys.dont_write_bytecode = True
HOME = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory', type=Path, help='Directory containing bundle.tar.gz and SHA256SUMS')
    parser.add_argument('--output', type=Path, help='New extraction directory (default: DIRECTORY/releases/field-import-01)')
    args = parser.parse_args()
    os.umask(0o077)
    if args.directory:
        directory = args.directory.resolve()
    elif HOME.name == 'onsite' and HOME.parent.name == 'tools':
        directory = HOME.parents[2]
    else:
        parser.error('Source checkout: pass --directory /absolute/delivery/directory')
    if sys.version_info < (3, 11):
        raise ValueError('Python 3.11 or newer is required')
    try:
        import yaml
    except ImportError:
        raise ValueError('PyYAML is missing from this Python; use the prepared onsite Python environment') from None
    print('PYTHON_READY', sys.version.split()[0], 'PyYAML', yaml.__version__, flush=True)
    import onsite

    archive, checksums = directory / 'bundle.tar.gz', directory / 'SHA256SUMS'
    output = (args.output or directory / 'releases/field-import-01').resolve()
    onsite.require(archive.is_file() and checksums.is_file(), 'Missing bundle.tar.gz or SHA256SUMS in ' + str(directory))
    reused = output.exists()
    if not reused:
        subprocess.run([sys.executable, str(HOME / 'onsite.py'), 'unpack', '--archive', str(archive),
                        '--checksums', str(checksums), '--output', str(output)], check=True)
    else:
        marker = output / 'unpack-result.json'
        onsite.require(marker.is_file(), 'Existing output has no completion record; choose a different --output')
        completed = json.loads(marker.read_text())
        matches = []
        for line in checksums.read_text().splitlines():
            match = re.fullmatch(r'([a-fA-F0-9]{64})\s+\*?(.+)', line)
            if match and match[2] == archive.name:
                matches.append(match[1].lower())
        onsite.require(matches == [completed['archive_sha256']], 'Existing extraction belongs to another delivery; choose a different --output')
        print('REUSE_EXTRACTION; verifying existing files, no overwrite', flush=True)
    completed = json.loads((output / 'unpack-result.json').read_text())
    relative = Path(completed['root'])
    onsite.require(not relative.is_absolute() and len(relative.parts) == 1 and relative.name not in ('.', '..'), 'Invalid unpack root')
    bundle = output / relative
    # New unpack already verified the full inventory. Reused directories need verification.
    descriptor = json.loads((bundle / 'bundle.json').read_text())
    onsite.require(descriptor.get('kind') == 'pxeye-nico-helm', 'Wrong bundle kind')
    if reused:
        onsite.verifier.verify(bundle)
    environment = directory / 'onsite/environment.sh'
    environment.parent.mkdir(parents=True, exist_ok=True)
    variables = {'KIT': str(HOME), 'BUNDLE': str(bundle),
                 'CONFIG': str(directory / 'onsite/site-config.json'),
                 'WORK': str(directory / 'onsite' / output.name)}
    for key in ('CONTEXT', 'NICO_NAMESPACE'):
        if os.environ.get(key):
            variables[key] = os.environ[key]
    text = '# Generated by prepare-bundle.sh; non-secret paths and context settings.\n'
    text += ''.join('export ' + key + '=' + shlex.quote(value) + '\n' for key, value in variables.items())
    with tempfile.NamedTemporaryFile(mode='w', dir=environment.parent, prefix='.environment-', delete=False) as stream:
        os.fchmod(stream.fileno(), 0o600); stream.write(text); temporary = Path(stream.name)
    temporary.replace(environment)
    print('BUNDLE_READY', descriptor['id'], descriptor['version'], bundle, flush=True)
    print('NEXT: source ' + shlex.quote(str(environment)), flush=True)


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.SubprocessError) as error:
        raise SystemExit(str(error)) from None
